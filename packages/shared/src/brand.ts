/**
 * الرمز كـ SVG نصي (للموقع والويدجت ومولّد الأيقونات).
 * pad: الهامش حول الشبكة بوحدة الخلية؛ radius نسبة زاوية المربع من عرضه.
 */
export function markSvg(opts: { ink: string; dot: string; bg?: string; pad?: number; radius?: number; size?: number }): string {
  const { ink, dot } = kuficPaths();
  const pad = opts.pad ?? (opts.bg ? 2.6 : 0);
  const n = KUFIC_SIZE + 2 * pad;
  const wh = opts.size ? ` width="${opts.size}" height="${opts.size}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${-pad} ${n} ${n}"${wh}>` +
    (opts.bg ? `<rect x="${-pad}" y="${-pad}" width="${n}" height="${n}" rx="${n * (opts.radius ?? 0.225)}" fill="${opts.bg}"/>` : '') +
    `<path d="${ink}" fill="${opts.ink}"/><path d="${dot}" fill="${opts.dot}"/></svg>`;
}
